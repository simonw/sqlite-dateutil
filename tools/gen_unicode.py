"""
Generate dateutil_unicode.h: the classes Python's str.isspace(),
str.isdigit() and str.isalpha() assign to non-ASCII code points, as
sorted ranges for binary search. dateutil's tokenizer is built on those
three methods.

    python3 tools/gen_unicode.py > dateutil_unicode.h
"""
import sys
import unicodedata


def cls(cp):
    ch = chr(cp)
    if ch.isspace():
        return "S"
    if ch.isdigit():
        return "D"
    if ch.isalpha():
        return "W"
    return None


ranges = []
for cp in range(0x80, 0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    k = cls(cp)
    if k is None:
        continue
    if ranges and ranges[-1][2] == k and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, k])

names = {"S": "CC_SPACE", "D": "CC_DIGIT", "W": "CC_WORD"}
out = sys.stdout
out.write("/* Generated by tools/gen_unicode.py from Python %s (Unicode %s).\n"
          "** Do not edit. Non-ASCII code points not listed are CC_OTHER. */\n"
          % (sys.version.split()[0], unicodedata.unidata_version))
out.write("static const struct { uint32_t lo, hi; unsigned char cls; } "
          "kUnicodeClass[] = {\n")
for lo, hi, k in ranges:
    out.write("  {0x%05X, 0x%05X, %s},\n" % (lo, hi, names[k]))
out.write("};\n")
