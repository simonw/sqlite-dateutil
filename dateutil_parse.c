/* Token helpers                                                       */

static int du_isdigit(int c){ return c >= '0' && c <= '9'; }
static int du_lower(int c){ return (c >= 'A' && c <= 'Z') ? c + 32 : c; }

/* Exact equality with a NUL-terminated literal. */
static int teq(Tok t, const char *s){
  size_t k = strlen(s);
  return (size_t)t.n == k && memcmp(t.z, s, k) == 0;
}
/* ASCII case-insensitive equality; s must be lower case. */
static int tieq(Tok t, const char *s){
  int i;
  for(i = 0; i < t.n; i++){
    if( s[i] == 0 || du_lower((unsigned char)t.z[i]) != s[i] ) return 0;
  }
  return s[i] == 0;
}
static int tsame(Tok a, Tok b){
  return a.n == b.n && memcmp(a.z, b.z, (size_t)a.n) == 0;
}
/* str.isdigit() for ASCII. */
static int tisdigits(Tok t){
  int i;
  if( t.n <= 0 ) return 0;
  for(i = 0; i < t.n; i++) if( !du_isdigit((unsigned char)t.z[i]) ) return 0;
  return 1;
}
static int tfind(Tok t, char c){
  int i;
  for(i = 0; i < t.n; i++) if( t.z[i] == c ) return i;
  return -1;
}

