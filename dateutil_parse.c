/* Calendar helpers                                                    */

static int du_leap(int64_t y){ return (y % 4 == 0 && y % 100 != 0) || y % 400 == 0; }
static int du_dim(int64_t y, int64_t m){
  static const int d[] = {31,28,31,30,31,30,31,31,30,31,30,31};
  if( m < 1 || m > 12 ) return 0;
  return d[m-1] + (m == 2 && du_leap(y));
}
/* Days since 1970-01-01 (Howard Hinnant's algorithm). Only called with
** validated dates in 1..9999. */
static int64_t du_days_from_civil(int64_t y, int64_t m, int64_t d){
  int64_t era, yoe, doy, doe;
  y -= m <= 2;
  era = (y >= 0 ? y : y - 399) / 400;
  yoe = y - era * 400;
  doy = (153 * (m + (m > 2 ? -3 : 9)) + 2) / 5 + d - 1;
  doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
  return era * 146097 + doe - 719468;
}
static void du_civil_from_days(int64_t z, int64_t *py, int64_t *pm, int64_t *pd){
  int64_t era, doe, yoe, y, doy, mp, d, m;
  z += 719468;
  era = (z >= 0 ? z : z - 146096) / 146097;
  doe = z - era * 146097;
  yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
  y = yoe + era * 400;
  doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
  mp = (5 * doy + 2) / 153;
  d = doy - (153 * mp + 2) / 5 + 1;
  m = mp + (mp < 10 ? 3 : -9);
  *py = y + (m <= 2);
  *pm = m;
  *pd = d;
}

/* parserinfo.convertyear() */
static int64_t du_convertyear(int64_t year, int century_specified, int cur){
  if( year < 100 && !century_specified ){
    year += cur / 100 * 100;
    if( year >= cur + 50 ) year -= 100;
    else if( year < cur - 50 ) year += 100;
  }
  return year;
}

