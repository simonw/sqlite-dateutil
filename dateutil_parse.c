/* Tokenizer: a port of _timelex.get_token()                           */

enum { CC_OTHER, CC_WORD, CC_DIGIT, CC_SPACE };

#include "dateutil_unicode.h"

/* Python's class for a non-ASCII code point, by binary search. */
static int du_unicode_class(uint32_t cp){
  size_t lo = 0, hi = sizeof(kUnicodeClass) / sizeof(kUnicodeClass[0]);
  while( lo < hi ){
    size_t mid = lo + (hi - lo) / 2;
    if( cp < kUnicodeClass[mid].lo ) hi = mid;
    else if( cp > kUnicodeClass[mid].hi ) lo = mid + 1;
    else return kUnicodeClass[mid].cls;
  }
  return CC_OTHER;
}

/* Classify the character at z[i] (n bytes total), as Python's isalpha(),
** isdigit() and isspace() would. Stores its length in bytes in *pLen
** (always >= 1 and never past n). Bytes that aren't valid UTF-8 (which
** Python could never see) are single-byte CC_OTHER characters. */
static int du_class(const unsigned char *z, int n, int i, int *pLen){
  static const uint32_t kMin[] = {0, 0, 0x80, 0x800, 0x10000};
  unsigned c = z[i];
  int len, k;
  uint32_t cp;
  *pLen = 1;
  if( c < 0x80 ){
    if( du_isdigit(c) ) return CC_DIGIT;
    if( (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ) return CC_WORD;
    if( c == ' ' || (c >= 0x09 && c <= 0x0D) || (c >= 0x1C && c <= 0x1F) ){
      return CC_SPACE;
    }
    return CC_OTHER;
  }
  if( c >= 0xC2 && c <= 0xDF ){ len = 2; cp = c & 0x1F; }
  else if( c >= 0xE0 && c <= 0xEF ){ len = 3; cp = c & 0x0F; }
  else if( c >= 0xF0 && c <= 0xF4 ){ len = 4; cp = c & 0x07; }
  else return CC_OTHER;
  if( len > n - i ) return CC_OTHER;
  for(k = 1; k < len; k++){
    unsigned d = z[i+k];
    if( (d & 0xC0) != 0x80 ) return CC_OTHER;
    cp = (cp << 6) | (d & 0x3F);
  }
  if( cp < kMin[len] || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF) ){
    return CC_OTHER;                    /* overlong, out of range, surrogate */
  }
  *pLen = len;
  return du_unicode_class(cp);
}

/* str.isdigit(): 1 if all ASCII digits, 2 if all digits by Python's
** rules but some aren't ASCII (int() then fails, except for the Nd
** digits we don't support), 0 otherwise. */
static int du_isdigit_tok(Tok t){
  const unsigned char *u = (const unsigned char*)t.z;
  int i = 0, len, ascii = 1;
  if( t.n <= 0 ) return 0;
  while( i < t.n ){
    if( du_class(u, t.n, i, &len) != CC_DIGIT ) return 0;
    if( len > 1 ) ascii = 0;
    i += len;
  }
  return ascii ? 1 : 2;
}

enum { ST_A, ST_0, ST_AD, ST_0D };

/* Split buf[0..n) into tokens. T must have room for n entries; every
** token uses at least one byte of buf, so at most n are written.
** buf may be modified (a ',' decimal separator becomes '.'). */
static int du_tokenize(char *buf, int n, Tok *T){
  const unsigned char *u = (const unsigned char*)buf;
  int L = 0, p = 0;
  while( p < n ){
    int clen, start = p, state, seen = 0, nch = 1, q, dots, s;
    int cls = du_class(u, n, p, &clen);
    if( cls == CC_SPACE ){ T[L++] = kTokSpace; p += clen; continue; }
    if( cls == CC_OTHER ){
      T[L].z = buf + p; T[L].n = clen; L++; p += clen; continue;
    }
    state = (cls == CC_WORD) ? ST_A : ST_0;
    p += clen;
    while( p < n ){
      int ch = u[p];
      cls = du_class(u, n, p, &clen);
      if( state == ST_A ){
        seen = 1;
        if( cls == CC_WORD ){ p += clen; nch++; }
        else if( ch == '.' ){ p++; state = ST_AD; }
        else break;
      }else if( state == ST_0 ){
        if( cls == CC_DIGIT ){ p += clen; nch++; }
        else if( ch == '.' || (ch == ',' && nch >= 2) ){  /* len(token) */
          p++; state = ST_0D;
        }
        else break;
      }else if( state == ST_AD ){
        seen = 1;
        if( ch == '.' || cls == CC_WORD ) p += clen;
        else if( cls == CC_DIGIT && u[p-1] == '.' ){ p += clen; state = ST_0D; }
        else break;
      }else{ /* ST_0D */
        if( ch == '.' || cls == CC_DIGIT ) p += clen;
        else if( cls == CC_WORD && u[p-1] == '.' ){ p += clen; state = ST_AD; }
        else break;
      }
    }
    if( state == ST_AD || state == ST_0D ){
      dots = 0;
      for(q = start; q < p; q++) if( buf[q] == '.' ) dots++;
      if( seen || dots > 1 || buf[p-1] == '.' || buf[p-1] == ',' ){
        /* _split_decimal: split on [.,], keeping separators, dropping
        ** empty pieces. */
        s = start;
        for(q = start; q < p; q++){
          if( buf[q] == '.' || buf[q] == ',' ){
            if( q > s ){ T[L].z = buf + s; T[L].n = q - s; L++; }
            T[L].z = buf + q; T[L].n = 1; L++;
            s = q + 1;
          }
        }
        if( p > s ){ T[L].z = buf + s; T[L].n = p - s; L++; }
        continue;
      }
      if( state == ST_0D && dots == 0 ){
        for(q = start; q < p; q++) if( buf[q] == ',' ) buf[q] = '.';
      }
    }
    T[L].z = buf + start; T[L].n = p - start; L++;
  }
  return L;
}

