static int64_t du_adjust_ampm(int64_t hour, int ampm){
  if( hour < 12 && ampm == 1 ) hour += 12;
  else if( hour == 12 && ampm == 0 ) hour = 0;
  return hour;
}

static int du_could_be_tzname(const Res *r, int check_offset, Tok t){
  int i;
  if( r->hour == DU_NONE || r->has_tzname ) return 0;
  if( check_offset && r->tzoffset != DU_NONE ) return 0;
  if( t.n > 5 ) return 0;
  if( teq(t, "UTC") || teq(t, "GMT") || teq(t, "Z") || teq(t, "z") ) return 1;
  for(i = 0; i < t.n; i++){
    if( t.z[i] < 'A' || t.z[i] > 'Z' ) return 0;
  }
  return 1;
}

/* parser._find_hms_idx(allow_jump=True) */
static int du_find_hms_idx(const Tok *T, int L, int idx){
  if( idx + 1 < L && lookup(T[idx+1], kHms) >= 0 ) return idx + 1;
  if( idx + 2 < L && teq(T[idx+1], " ") && lookup(T[idx+2], kHms) >= 0 ){
    return idx + 2;
  }
  if( idx > 0 && lookup(T[idx-1], kHms) >= 0 ) return idx - 1;
  if( idx > 1 && idx == L - 1 && teq(T[idx-1], " ")
   && lookup(T[idx-2], kHms) >= 0 ){
    return idx - 2;
  }
  return -1;
}

/* parser._assign_hms() */
static int du_assign_hms(Res *r, Tok s, const Num *v, int hms){
  if( hms == 0 ){
    r->hour = v->ip;
    if( v->fnz ) r->minute = du_sixty(v);
  }else if( hms == 1 ){
    r->minute = v->ip;
    r->second = v->fnz ? du_sixty(v) : DU_NONE;
  }else if( hms == 2 ){
    return du_parsems(s.z, s.n, &r->second, &r->us);
  }
  return 1;
}

/* parser._parse_numeric_token(). Returns the new index, or -1 where
** dateutil would raise ValueError/IndexError. */
static int du_numeric(Tok *T, int L, int idx, const Num *val,
                      Ymd *Y, Res *r, int fuzzy){
  Tok s = T[idx];
  int len_li = s.n, a, hi, m;

  if( Y->n == 3 && (len_li == 2 || len_li == 4) && r->hour == DU_NONE
   && (idx + 1 >= L
       || (!teq(T[idx+1], ":") && lookup(T[idx+1], kHms) < 0)) ){
    /* 19990101T23[59] */
    if( !du_uint(s.z, 2, &r->hour) ) return -1;
    if( len_li == 4 && !du_uint(s.z + 2, 2, &r->minute) ) return -1;

  }else if( len_li == 6 || (len_li > 6 && tfind(s, '.') == 6) ){
    /* YYMMDD or HHMMSS[.ss] */
    if( Y->n == 0 && tfind(s, '.') < 0 ){
      if( !ymd_append_str(Y, s.z, 2, 0)
       || !ymd_append_str(Y, s.z + 2, 2, 0)
       || !ymd_append_str(Y, s.z + 4, len_li - 4, 0) ) return -1;
    }else{
      if( !du_uint(s.z, 2, &r->hour)
       || !du_uint(s.z + 2, 2, &r->minute)
       || !du_parsems(s.z + 4, len_li - 4, &r->second, &r->us) ) return -1;
    }

  }else if( len_li == 8 || len_li == 12 || len_li == 14 ){
    /* YYYYMMDD[hhmm[ss]] */
    if( !ymd_append_str(Y, s.z, 4, 'Y')
     || !ymd_append_str(Y, s.z + 4, 2, 0)
     || !ymd_append_str(Y, s.z + 6, 2, 0) ) return -1;
    if( len_li > 8 ){
      if( !du_uint(s.z + 8, 2, &r->hour)
       || !du_uint(s.z + 10, 2, &r->minute) ) return -1;
      if( len_li > 12 && !du_uint(s.z + 12, len_li - 12, &r->second) ){
        return -1;
      }
    }

  }else if( (hi = du_find_hms_idx(T, L, idx)) >= 0 ){
    /* HH[ ]h or MM[ ]m or SS[.ss][ ]s */
    int hms;
    if( hi > idx ){ hms = lookup(T[hi], kHms); idx = hi; }
    else hms = lookup(T[hi], kHms) + 1;
    if( !du_assign_hms(r, s, val, hms) ) return -1;

  }else if( idx + 2 < L && teq(T[idx+1], ":") ){
    /* HH:MM[:SS[.ss]] */
    Num v2;
    r->hour = val->ip;
    if( !du_num(T[idx+2], &v2) ) return -1;
    r->minute = v2.ip;
    r->second = v2.fnz ? du_sixty(&v2) : DU_NONE;
    if( idx + 4 < L && teq(T[idx+3], ":") ){
      if( !du_parsems(T[idx+4].z, T[idx+4].n, &r->second, &r->us) ) return -1;
      idx += 2;
    }
    idx += 2;

  }else if( idx + 1 < L
         && (teq(T[idx+1], "-") || teq(T[idx+1], "/") || teq(T[idx+1], ".")) ){
    Tok sep = T[idx+1];
    if( !ymd_append_str(Y, s.z, s.n, 0) ) return -1;
    if( idx + 2 < L && lookup(T[idx+2], kJump) < 0 ){
      if( du_isdigit_tok(T[idx+2]) ){
        /* 01-01[-01]; int() rejects non-ASCII digits */
        if( !ymd_append_str(Y, T[idx+2].z, T[idx+2].n, 0) ) return -1;
      }else{
        /* 01-Jan[-01] */
        m = lookup(T[idx+2], kMonths);
        if( m < 0 || !ymd_push(Y, m, 'M') ) return -1;
      }
      if( idx + 3 < L && tsame(T[idx+3], sep) ){
        if( idx + 4 >= L ) return -1;
        m = lookup(T[idx+4], kMonths);
        if( m >= 0 ){
          if( !ymd_push(Y, m, 'M') ) return -1;
        }else if( !ymd_append_str(Y, T[idx+4].z, T[idx+4].n, 0) ){
          return -1;
        }
        idx += 2;
      }
      idx += 1;
    }
    idx += 1;

  }else if( idx + 1 >= L || lookup(T[idx+1], kJump) >= 0 ){
    if( idx + 2 < L && (a = lookup(T[idx+2], kAmpm)) >= 0 ){
      /* 12 am */
      r->hour = du_adjust_ampm(val->ip, a);
      idx += 1;
    }else{
      /* Year, month or day */
      if( !ymd_append_num(Y, val) ) return -1;
    }
    idx += 1;

  }else if( (a = lookup(T[idx+1], kAmpm)) >= 0 && val->ip < 24 ){
    /* 12am */
    r->hour = du_adjust_ampm(val->ip, a);
    idx += 1;

  }else if( ymd_could_be_day(Y, val) ){
    if( !ymd_append_num(Y, val) ) return -1;

  }else if( !fuzzy ){
    return -1;
  }
  return idx;
}

/* parser._parse() + validate() + _build_naive() + _build_tzaware(),
** writing isoformat() into zOut. Returns 1 on success, 0 on failure. */
static int du_run(Tok *T, int L, int flags, const DuToday *td,
                  char *zOut, size_t nOut){
  const int fuzzy = (flags & DU_FUZZY) != 0;
  const int dayfirst = (flags & DU_DAYFIRST) != 0;
  const int yearfirst = (flags & DU_YEARFIRST) != 0;
  Res r;
  Ymd Y;
  int i = 0, v;
  int64_t yr, mo, dy, hh, mi, ss, us;

  memset(&Y, 0, sizeof(Y));
  Y.yi = Y.mi = Y.di = -1;
  memset(&r, 0, sizeof(r));
  r.year = r.month = r.day = r.hour = r.minute = r.second = r.us = DU_NONE;
  r.tzoffset = DU_NONE;
  r.weekday = r.ampm = -1;

  while( i < L ){
    Tok t = T[i];
    Num num;
    int nk = du_numkind(t, &num);
    if( nk < 0 ) return 0;
    if( nk > 0 ){
      i = du_numeric(T, L, i, &num, &Y, &r, fuzzy);
      if( i < 0 ) return 0;

    }else if( (v = lookup(t, kWeekdays)) >= 0 ){
      r.weekday = v;

    }else if( (v = lookup(t, kMonths)) >= 0 ){
      if( !ymd_push(&Y, v, 'M') ) return 0;
      if( i + 1 < L ){
        if( teq(T[i+1], "-") || teq(T[i+1], "/") ){
          /* Jan-01[-99] */
          Tok sep = T[i+1];
          if( i + 2 >= L || !ymd_append_str(&Y, T[i+2].z, T[i+2].n, 0) ){
            return 0;
          }
          if( i + 3 < L && tsame(T[i+3], sep) ){
            if( i + 4 >= L || !ymd_append_str(&Y, T[i+4].z, T[i+4].n, 0) ){
              return 0;
            }
            i += 2;
          }
          i += 2;
        }else if( i + 4 < L && teq(T[i+1], " ") && teq(T[i+3], " ")
               && lookup(T[i+2], kPertain) >= 0 ){
          /* Jan of 01 */
          int dk = du_isdigit_tok(T[i+4]);
          if( dk == 2 ) return 0;             /* int() raises */
          if( dk == 1 ){
            int64_t yv = 0;
            du_uint(T[i+4].z, T[i+4].n, &yv);
            yv = du_convertyear(yv, 0, td->cur_year);
            if( yv >= 100 ) Y.century = 1;  /* len(str(year)) > 2 */
            if( !ymd_push(&Y, yv, 'Y') ) return 0;
          }
          i += 4;
        }
      }

    }else if( (v = lookup(t, kAmpm)) >= 0 ){
      int valid = 1;
      if( fuzzy && r.ampm >= 0 ) valid = 0;
      if( r.hour == DU_NONE || r.hour > 12 ){
        if( !fuzzy ) return 0;
        valid = 0;
      }
      if( valid ){
        r.hour = du_adjust_ampm(r.hour, v);
        r.ampm = v;
      }

    }else if( du_could_be_tzname(&r, 1, t) ){
      r.tzname = t;
      r.has_tzname = 1;
      /* parserinfo.tzoffset() compares against the lower-cased UTCZONE
      ** keys without lower-casing, so only "z" matches here. */
      r.tzoffset = teq(t, "z") ? 0 : DU_NONE;
      if( i + 1 < L && (teq(T[i+1], "+") || teq(T[i+1], "-")) ){
        /* GMT+3 means "my time +3 is GMT": flip the sign */
        T[i+1] = teq(T[i+1], "+") ? kTokMinus : kTokPlus;
        r.tzoffset = DU_NONE;
        if( lookup(t, kUtcZone) >= 0 ) r.has_tzname = 0;
      }

    }else if( r.hour != DU_NONE && (teq(t, "+") || teq(t, "-")) ){
      int sign = teq(t, "+") ? 1 : -1;
      int64_t ho, mo2;
      Tok a;
      if( i + 1 >= L ) return 0;
      a = T[i+1];
      if( a.n == 4 ){
        /* -0300 */
        if( !du_uint(a.z, 2, &ho) || !du_uint(a.z + 2, 2, &mo2) ) return 0;
      }else if( i + 2 < L && teq(T[i+2], ":") ){
        /* -03:00 */
        if( !du_uint(a.z, a.n, &ho) ) return 0;
        if( i + 3 >= L || !du_uint(T[i+3].z, T[i+3].n, &mo2) ) return 0;
        i += 2;
      }else if( a.n <= 2 ){
        /* -[0]3 */
        if( !du_uint(a.z, a.n, &ho) ) return 0;
        mo2 = 0;
      }else{
        return 0;
      }
      /* Both values are <= 10^15, so this cannot overflow. */
      r.tzoffset = sign * (ho * 3600 + mo2 * 60);
      /* -0300 (BRST) */
      if( i + 5 < L && lookup(T[i+2], kJump) >= 0 && teq(T[i+3], "(")
       && teq(T[i+5], ")") && T[i+4].n >= 3
       && du_could_be_tzname(&r, 0, T[i+4]) ){
        r.tzname = T[i+4];
        r.has_tzname = 1;
        i += 4;
      }
      i += 1;

    }else if( !(lookup(t, kJump) >= 0 || fuzzy) ){
      return 0;
    }
    i += 1;
  }

  if( !ymd_resolve(&Y, yearfirst, dayfirst, &r.year, &r.month, &r.day) ){
    return 0;
  }

  /* parserinfo.validate() */
  if( r.year != DU_NONE ) r.year = du_convertyear(r.year, Y.century, td->cur_year);
  if( (r.tzoffset == 0 && !r.has_tzname)
   || (r.has_tzname && (teq(r.tzname, "Z") || teq(r.tzname, "z"))) ){
    r.tzname = kTokUTC;
    r.has_tzname = 1;
    r.tzoffset = 0;
  }else if( r.tzoffset != 0 && r.has_tzname && lookup(r.tzname, kUtcZone) >= 0 ){
    r.tzoffset = 0;
  }

  /* len(res) == 0: "String does not contain a date" */
  if( r.year == DU_NONE && r.month == DU_NONE && r.day == DU_NONE
   && r.weekday < 0 && r.hour == DU_NONE && r.minute == DU_NONE
   && r.second == DU_NONE && r.us == DU_NONE && !r.has_tzname
   && r.tzoffset == DU_NONE && r.ampm < 0 ){
    return 0;
  }

  /* _build_naive(): default.replace(**repl) */
  yr = r.year != DU_NONE ? r.year : td->year;
  mo = r.month != DU_NONE ? r.month : td->month;
  if( r.day == DU_NONE ){
    int dim = du_dim(yr, mo);
    if( dim == 0 ) return 0;            /* monthrange() raises */
    dy = td->day > dim ? dim : td->day;
  }else{
    dy = r.day;
  }
  hh = r.hour != DU_NONE ? r.hour : 0;
  mi = r.minute != DU_NONE ? r.minute : 0;
  ss = r.second != DU_NONE ? r.second : 0;
  us = r.us != DU_NONE ? r.us : 0;
  if( yr < 1 || yr > 9999 || mo < 1 || mo > 12 || dy < 1 || dy > du_dim(yr, mo)
   || hh < 0 || hh > 23 || mi < 0 || mi > 59 || ss < 0 || ss > 59
   || us < 0 || us > 999999 ){
    return 0;
  }

  /* relativedelta(weekday=N): move forward to the next such weekday */
  if( r.weekday >= 0 && r.day == DU_NONE ){
    int64_t days = du_days_from_civil(yr, mo, dy);
    int dow = (int)(((days % 7) + 7 + 3) % 7);   /* 1970-01-01 was a Thu */
    days += (7 - dow + r.weekday) % 7;
    du_civil_from_days(days, &yr, &mo, &dy);
    if( yr > 9999 ) return 0;                    /* OverflowError */
  }

  {
    char tz[16] = "";
    int64_t off = r.tzoffset;
    int pos;
    if( off != DU_NONE ){
      int64_t a = off < 0 ? -off : off;
      if( a >= 86400 ) return 0;  /* utcoffset() must be within +/-24h */
      snprintf(tz, sizeof(tz), "%c%02d:%02d", off < 0 ? '-' : '+',
               (int)(a / 3600), (int)((a % 3600) / 60));
    }
    pos = snprintf(zOut, nOut, "%04d-%02d-%02dT%02d:%02d:%02d",
                   (int)yr, (int)mo, (int)dy, (int)hh, (int)mi, (int)ss);
    if( pos < 0 || (size_t)pos >= nOut ) return 0;
    if( us ){
      int k = snprintf(zOut + pos, nOut - pos, ".%06d", (int)us);
      if( k < 0 || (size_t)k >= nOut - pos ) return 0;
      pos += k;
    }
    if( tz[0] ){
      int k = snprintf(zOut + pos, nOut - pos, "%s", tz);
      if( k < 0 || (size_t)k >= nOut - pos ) return 0;
    }
  }
  return 1;
}

/* Parse nIn bytes at zIn. Returns 1 and writes a NUL-terminated ISO
** string to zOut (nOut >= 40 is always enough) on success, 0 if the
** input can't be parsed, -1 on out-of-memory. */
static int du_parse(const char *zIn, int nIn, int flags, const DuToday *td,
                    char *zOut, size_t nOut){
  char sbuf[DU_STACK];
  Tok stok[DU_STACK];
  char *buf = sbuf;
  Tok *T = stok;
  int i, n = 0, L, rc;

  if( zIn == 0 || nIn <= 0 || nIn > DATEUTIL_MAX_INPUT ) return 0;
  if( nIn > DU_STACK ){
    buf = (char*)DU_MALLOC((size_t)nIn);
    T = (Tok*)DU_MALLOC(sizeof(Tok) * (size_t)nIn);
    if( buf == 0 || T == 0 ){
      if( buf ) DU_FREE(buf);
      if( T ) DU_FREE(T);
      return -1;
    }
  }
  /* _timelex skips NUL characters entirely. */
  for(i = 0; i < nIn; i++){
    if( zIn[i] ) buf[n++] = zIn[i];
  }
  L = du_tokenize(buf, n, T);
  rc = du_run(T, L, flags, td, zOut, nOut);
  if( buf != sbuf ) DU_FREE(buf);
  if( T != stok ) DU_FREE(T);
  return rc;
}

/* datetime.datetime.now() in local time, like dateutil's default. */
static void du_today(DuToday *td){
  time_t now = time(0);
  struct tm tm;
#if defined(_WIN32)
  localtime_s(&tm, &now);
#else
  localtime_r(&now, &tm);
#endif
  td->year = tm.tm_year + 1900;
  td->month = tm.tm_mon + 1;
  td->day = tm.tm_mday;
  td->cur_year = td->year;
}

