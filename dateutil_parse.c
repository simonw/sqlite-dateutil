/* Numbers                                                             */

/* Strict int(): one or more ASCII digits, nothing else. Saturates at
** DU_CLAMP so it can never overflow. */
static int du_uint(const char *z, int n, int64_t *out){
  int64_t v = 0;
  int i;
  if( n <= 0 ) return 0;
  for(i = 0; i < n; i++){
    int c = (unsigned char)z[i];
    if( !du_isdigit(c) ) return 0;
    if( v < DU_CLAMP ){
      v = v * 10 + (c - '0');
      if( v > DU_CLAMP ) v = DU_CLAMP;
    }
  }
  *out = v;
  return 1;
}

/* A Decimal value: integer part plus the fractional digits. */
typedef struct {
  int64_t ip;        /* int(value), saturated */
  const char *f;     /* fractional digits */
  int nf;            /* number of fractional digits */
  int fnz;           /* value % 1 != 0 */
} Num;

/* Accepts DIGITS or DIGITS.DIGITS, the only numeric tokens _timelex
** can produce. */
static int du_num(Tok t, Num *v){
  int i = 0, j;
  while( i < t.n && du_isdigit((unsigned char)t.z[i]) ) i++;
  if( i == 0 ) return 0;
  v->f = 0; v->nf = 0; v->fnz = 0;
  if( i < t.n ){
    if( t.z[i] != '.' || i + 1 == t.n ) return 0;
    for(j = i + 1; j < t.n; j++){
      if( !du_isdigit((unsigned char)t.z[j]) ) return 0;
      if( t.z[j] != '0' ) v->fnz = 1;
    }
    v->f = t.z + i + 1;
    v->nf = t.n - i - 1;
  }
  return du_uint(t.z, i, &v->ip);
}

/* Is this token one that float() would accept? 1 = numeric, 0 = not,
** -1 = nan/inf, which float() accepts but Decimal rejects, so dateutil
** fails outright (even with fuzzy=True). */
static int du_numkind(Tok t, Num *v){
  if( du_num(t, v) ) return 1;
  if( tieq(t, "nan") || tieq(t, "inf") || tieq(t, "infinity") ) return -1;
  return 0;
}

/* int(60 * (value % 1)), computed exactly from the decimal digits. */
static int64_t du_sixty(const Num *v){
  int64_t carry = 0;
  int j;
  for(j = v->nf - 1; j >= 0; j--){
    carry = ((v->f[j] - '0') * 60 + carry) / 10;
  }
  return carry;
}

static int num_gt(const Num *v, int64_t n){ return v->ip > n || (v->ip == n && v->fnz); }
static int num_le(const Num *v, int64_t n){ return v->ip < n || (v->ip == n && !v->fnz); }

/* _parsems(): "S" or "S.FFFFFF" -> seconds, microseconds. */
static int du_parsems(const char *z, int n, int64_t *sec, int64_t *us){
  int d = -1, i, k;
  int64_t f = 0;
  for(i = 0; i < n; i++){
    if( z[i] == '.' ){
      if( d >= 0 ) return 0;          /* i, f = value.split(".") fails */
      d = i;
    }
  }
  if( d < 0 ){
    if( !du_uint(z, n, sec) ) return 0;
    *us = 0;
    return 1;
  }
  if( !du_uint(z, d, sec) ) return 0;
  /* int(f.ljust(6, "0")[:6]) */
  for(k = 0; k < 6; k++){
    int c = (d + 1 + k < n) ? (unsigned char)z[d+1+k] : '0';
    if( !du_isdigit(c) ) return 0;
    f = f * 10 + (c - '0');
  }
  *us = f;
  return 1;
}

