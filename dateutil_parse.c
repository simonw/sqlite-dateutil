/*
** dateutil_parse.c -- a SQLite extension that ports python-dateutil's
** dateutil.parser.parse() to C.
**
** SQL functions (all return an ISO 8601 string, or NULL if unparseable):
**
**   dateutil_parse(text)
**   dateutil_parse_fuzzy(text)            -- like parse(text, fuzzy=True)
**   dateutil_parse_dayfirst(text)         -- like parse(text, dayfirst=True)
**   dateutil_parse_fuzzy_dayfirst(text)   -- both
**
** The output matches datetime.isoformat() of the Python result, e.g.
**   '2003-09-25T10:49:41'  or  '2003-09-25T10:49:41.502000-03:00'
**
** This is a port of the algorithm in dateutil/parser/_parser.py (2.9.0):
** the _timelex tokenizer, parser._parse(), _parse_numeric_token(),
** _ymd.resolve_ymd(), parserinfo.validate() and parser._build_naive().
** Missing fields come from today's local date at midnight, as in dateutil.
**
** Design priorities, in order:
**   1. Memory safety. Every token index is bounds-checked, every int
**      conversion is strict and saturating (no overflow is possible),
**      all buffers have known sizes, and there is no recursion.
**   2. Performance. One pass to tokenize, one pass to parse (O(n) time).
**      Inputs up to DU_STACK bytes need no heap allocation at all.
**   3. Fidelity to dateutil, wherever it is reasonable.
**
** Known differences from dateutil (by design):
**   - No tzinfos= support. A tz name that dateutil can't resolve without
**     tzinfos (e.g. "EST") gives a naive result, as dateutil does. But
**     dateutil also maps names in time.tzname (the machine's local zone)
**     to tzlocal(); this extension does not, because that makes results
**     depend on the server's TZ setting.
**   - The tokenizer classifies characters exactly as Python's isalpha(),
**     isdigit() and isspace() do (table generated by tools/gen_unicode.py),
**     but only ASCII digits can form numbers. Python's float()/int() also
**     accept other decimal digits, e.g. '\uff12\uff10\uff10\uff13'
**     (full-width 2003); those give NULL here.
**   - Numbers are exact (no float rounding). Integers saturate at 10^15,
**     which only affects values that are invalid anyway. Python's Decimal
**     uses 28 digits of precision, so fractions longer than that may
**     round differently.
**   - Inputs longer than DATEUTIL_MAX_INPUT bytes (default 64 KiB) return
**     NULL.
*/
