/* Returns the table value, or -1 if not found. */
static int lookup(Tok t, const DuName *tab){
  if( t.n < 1 || t.n > 9 ) return -1;   /* longest name is 9 bytes */
  for(; tab->name; tab++){
    if( tieq(t, tab->name) ) return tab->val;
  }
  return -1;
}

