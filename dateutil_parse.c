/* _ymd                                                                */

typedef struct {
  int64_t v[3];
  int n;
  int century;
  int yi, mi, di;      /* ystridx, mstridx, dstridx; -1 = None */
} Ymd;

/* list.append + label bookkeeping. dateutil would let the list grow past
** three items but then always fails in resolve_ymd(), so we fail now. */
static int ymd_push(Ymd *Y, int64_t val, int label){
  if( Y->n >= 3 ) return 0;
  Y->v[Y->n++] = val;
  if( label == 'M' ){ if( Y->mi >= 0 ) return 0; Y->mi = Y->n - 1; }
  else if( label == 'Y' ){ if( Y->yi >= 0 ) return 0; Y->yi = Y->n - 1; }
  return 1;
}
/* _ymd.append(str_value, label) */
static int ymd_append_str(Ymd *Y, const char *z, int n, int label){
  Tok t; int64_t v;
  t.z = z; t.n = n;
  if( tisdigits(t) && n > 2 ){ Y->century = 1; label = 'Y'; }
  if( !du_uint(z, n, &v) ) return 0;
  return ymd_push(Y, v, label);
}
/* _ymd.append(decimal_value) */
static int ymd_append_num(Ymd *Y, const Num *v){
  int label = 0;
  if( num_gt(v, 100) ){ Y->century = 1; label = 'Y'; }
  return ymd_push(Y, v->ip, label);
}
static int ymd_could_be_day(const Ymd *Y, const Num *v){
  int lim;
  if( Y->di >= 0 ) return 0;
  if( Y->mi < 0 ) lim = 31;
  else if( Y->yi < 0 ) lim = du_dim(2000, Y->v[Y->mi]);
  else lim = du_dim(Y->v[Y->yi], Y->v[Y->mi]);
  return v->ip >= 1 && num_le(v, lim);
}

/* _ymd.resolve_ymd() */
static int ymd_resolve(const Ymd *Y, int yearfirst, int dayfirst,
                       int64_t *py, int64_t *pm, int64_t *pd){
  const int64_t *s = Y->v;
  int n = Y->n, mi = Y->mi;
  int ns = (Y->yi >= 0) + (Y->mi >= 0) + (Y->di >= 0);
  *py = *pm = *pd = DU_NONE;

  if( (n == ns && ns > 0) || (n == 3 && ns == 2) ){
    int yi = Y->yi, di = Y->di, x;
    if( n == 3 && ns == 2 ){
      for(x = 0; x < 3; x++){
        if( x != yi && x != mi && x != di ) break;
      }
      if( yi < 0 ) yi = x; else if( mi < 0 ) mi = x; else di = x;
    }
    if( yi >= 0 ) *py = s[yi];
    if( mi >= 0 ) *pm = s[mi];
    if( di >= 0 ) *pd = s[di];
    return 1;
  }
  if( n > 3 ) return 0;
  if( n == 1 || (mi >= 0 && n == 2) ){
    int64_t other;
    if( mi >= 0 ){
      *pm = s[mi];
      other = s[(mi - 1 + n) % n];      /* self[mstridx - 1] */
    }else{
      other = s[0];
    }
    if( n > 1 || mi < 0 ){
      if( other > 31 ) *py = other; else *pd = other;
    }
  }else if( n == 2 ){
    if( s[0] > 31 ){ *py = s[0]; *pm = s[1]; }
    else if( s[1] > 31 ){ *pm = s[0]; *py = s[1]; }
    else if( dayfirst && s[1] <= 12 ){ *pd = s[0]; *pm = s[1]; }
    else { *pm = s[0]; *pd = s[1]; }
  }else if( n == 3 ){
    if( mi == 0 ){
      if( s[1] > 31 ){ *pm = s[0]; *py = s[1]; *pd = s[2]; }
      else { *pm = s[0]; *pd = s[1]; *py = s[2]; }
    }else if( mi == 1 ){
      if( s[0] > 31 || (yearfirst && s[2] <= 31) ){
        *py = s[0]; *pm = s[1]; *pd = s[2];
      }else{
        *pd = s[0]; *pm = s[1]; *py = s[2];
      }
    }else if( mi == 2 ){
      if( s[1] > 31 ){ *pd = s[0]; *py = s[1]; *pm = s[2]; }
      else { *py = s[0]; *pd = s[1]; *pm = s[2]; }
    }else{
      if( s[0] > 31 || Y->yi == 0 || (yearfirst && s[1] <= 12 && s[2] <= 31) ){
        if( dayfirst && s[2] <= 12 ){ *py = s[0]; *pd = s[1]; *pm = s[2]; }
        else { *py = s[0]; *pm = s[1]; *pd = s[2]; }
      }else if( s[0] > 12 || (dayfirst && s[1] <= 12) ){
        *pd = s[0]; *pm = s[1]; *py = s[2];
      }else{
        *pm = s[0]; *pd = s[1]; *py = s[2];
      }
    }
  }
  return 1;
}

